#!/usr/bin/env node
/**
 * Regenerates src/lib/rea-docs.ts from the local rea skill directory.
 *
 *   node scripts/sync-rea-docs.mjs [--src <dir>]
 *
 * Source defaults to ../opencode-skills/rea (sibling of this repo) and can be
 * overridden with REA_SRC. Output is deterministic: same sources in, same file out.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'src/lib/rea-docs.ts');

const argv = process.argv.slice(2);
const flagIndex = argv.indexOf('--src');
const SRC = path.resolve(
  flagIndex >= 0 && argv[flagIndex + 1]
    ? argv[flagIndex + 1]
    : process.env.REA_SRC || path.join(ROOT, '..', 'opencode-skills', 'rea')
);

const FILES = [
  ['skill', 'SKILL.md', 'SKILL.md'],
  ['method', 'method.md', 'references/method.md'],
  ['ledger', 'ledger-template.md', 'references/ledger-template.md'],
  ['paging', 'evidence-paging.md', 'references/evidence-paging.md'],
  ['binary', 'binary-cli.md', 'references/binary-cli.md']
];

const EMOJI = /[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{FE0F}]/u;

if (!fs.existsSync(SRC)) {
  console.error(`Source directory not found: ${SRC}`);
  process.exit(1);
}

const sections = FILES.map(([id, label, rel]) => {
  const file = path.join(SRC, rel);
  if (!fs.existsSync(file)) throw new Error(`${rel}: not found in ${SRC}`);
  const content = fs.readFileSync(file, 'utf8');
  if (EMOJI.test(content)) throw new Error(`${rel}: emoji found — skill copy must stay emoji-free`);
  return { id, label, path: rel, content };
});

const version = /# REA .*\((v\d+)/.exec(sections[0].content)?.[1] ?? 'v7';

const entries = sections
  .map(
    (doc) => `  {
    id: ${JSON.stringify(doc.id)},
    label: ${JSON.stringify(doc.label)},
    path: ${JSON.stringify(doc.path)},
    content: ${JSON.stringify(doc.content)},
  }`
  )
  .join(',\n');

const output = `import type { ReaDocSection } from './types';

// Generated by scripts/sync-rea-docs.mjs — do not edit by hand.
export const REA_VERSION: string = ${JSON.stringify(version)};
export const REA_DOCS: ReaDocSection[] = [
${entries},
];
`;

fs.writeFileSync(OUT, output);
console.log(`Synced ${sections.length} REA documents (${version}) from ${SRC}`);
console.log(`Wrote ${path.relative(ROOT, OUT)} (${(output.length / 1024).toFixed(1)} kB)`);
